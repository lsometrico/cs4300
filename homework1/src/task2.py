# demonstrate the various basic data types in python
def interger():
    return 67

def float_point():
    return 5.49

def string():
    return "Pain, agony and suffering"

def boolean():
    return False 

def main():
    int_value = interger()
    floating_point = float_point()
    string_get = string()
    boolean_get = boolean()

    print(int_value)
    print(floating_point)
    print(string_get)
    print(boolean_get)

if __name__ == "__main__":
    main()